/** A page of a channel tab: videos (also Shorts and live streams) or playlists; [continuation] asks for the next page. */
data class ExcorChannelPage(val items: List<ExcorSearchResult>, val continuation: String?)

/**
 * What a YouTube search looks for. The params are the ones YouTube's own search page sends for its "Type" filters
 * (its response of 2026-10-27; `ExcorSearchPage.filters` has the current ones, and the other groups).
 */
enum class ExcorSearchType(internal val params: String) {
    VIDEOS("EgIQAQ%3D%3D"),

    /** Shorts come in `ExcorSearchPage.shorts`, as YouTube sends them: in grids, apart from the results. */
    SHORTS("EgIQCQ%3D%3D"),
    CHANNELS("EgIQAg%3D%3D"),
    PLAYLISTS("EgIQAw%3D%3D"),
    MOVIES("EgIQBA%3D%3D"),
}

/**
 * One of the filters YouTube offers for a search (type, duration, upload date, features, sort order), in YouTube's
 * words in the session's language. [params] asks for the search with it and with the filters already applied; it is
 * null when it cannot be asked: one already [selected], or one that does not go with them (durations for channels).
 */
data class ExcorSearchFilter(val group: String?, val label: String, val params: String?, val selected: Boolean)

/**
 * A page of search results; [continuation] asks for the next one and is null on the last. [shorts] are the Shorts
 * YouTube put in grids beside the results; [filters] are offered on the first page of a YouTube search only.
 */
data class ExcorSearchPage(
    val results: List<ExcorSearchResult>,
    val continuation: String?,
    val shorts: List<ExcorSearchResult> = emptyList(),
    val filters: List<ExcorSearchFilter> = emptyList(),
)

/** What a YouTube or YouTube Music link or ID points at; see `Excor.parse`. */
sealed class ExcorRef {
    /** A video, possibly opened from a list ([playlistId]) at [startSeconds]. */
    data class Video(val videoId: String, val playlistId: String? = null, val startSeconds: Int? = null) : ExcorRef()

    data class Playlist(val playlistId: String) : ExcorRef()

    /** A YouTube Music album page (`MPREb_…`). */
    data class Album(val browseId: String) : ExcorRef()

    /** A mix (`RD…`): a list YouTube generates from a seed. */
    data class Mix(val playlistId: String) : ExcorRef()

    /** A channel (`UC…`), which on YouTube Music is an artist page; see `Excor.artist`. */
    data class Channel(val channelId: String) : ExcorRef()
}

