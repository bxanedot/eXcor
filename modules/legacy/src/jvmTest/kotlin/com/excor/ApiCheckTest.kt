package com.excor

import com.excor.internal.primary.extraction.PoTokenResult
import com.excor.internal.primary.extraction.TokenProvider
import com.excor.internal.primary.extraction.TokenProviderCapabilities
import com.excor.internal.primary.extraction.strategy.PoTokenProviderKind
import kotlinx.coroutines.runBlocking
import okhttp3.OkHttpClient
import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNull

/** Compiles against every member of the public API the host app uses (BRIEF section 3). */
class ApiCheckTest {
    private val store = object : ExcorConfigStore {
        override val enabled: Boolean = false
        override fun getString(key: String): String? = null
        override fun getLong(key: String): Long? = null
        override fun putString(key: String, value: String) {}
        override fun putLong(key: String, value: Long) {}
    }

    private val tokens = object : TokenProvider {
        override suspend fun getPoToken(videoId: String, visitorData: String, cookie: String?): PoTokenResult? = null
    }

    private val host = object : ExcorHost {
        override suspend fun session() = ExcorSession(cookie = null, visitorData = null, region = "US", language = "en")
        override val configStore: ExcorConfigStore = store
        override fun nowMs(): Long = 0
        override fun log(level: ExcorLogLevel, message: String, trackId: String?) {}
        override val tokenProvider: TokenProvider = tokens
        override val filesDir: File? = null
        override val httpClient: OkHttpClient = OkHttpClient()
    }

    @Test
    fun publicApiCompiles() = runBlocking {
        val stream = ExcorStream(
            videoId = "v", url = "u", kbps = 1, mimeType = "m", loudnessDb = null,
            clientName = "c", profileId = "p", headers = emptyMap(),
        )
        val (videoId, url, kbps, mimeType, loudnessDb, clientName, profileId, headers) = stream
        listOf<Any?>(videoId, url, kbps, mimeType, loudnessDb, clientName, profileId, headers)

        val video = ExcorVideoStream(
            videoId = "v", url = "u", width = 1, height = 1, fps = 1, kbps = 1, mimeType = "m", audio = stream,
            clientName = "c", profileId = "p", headers = emptyMap(),
        )
        listOf<Any?>(video.videoId, video.url, video.width, video.height, video.fps, video.kbps, video.mimeType, video.audio, video.clientName, video.profileId, video.headers)
        val thumbnail = ExcorThumbnail(url = "u", width = 1, height = 1)
        val caption = ExcorCaptionTrack(url = "u", languageCode = "en", name = null, autoGenerated = true, isTranslatable = true)
        listOf<Any?>(caption.isTranslatable, caption.urlFor(ExcorCaptionFormat.VTT), caption.urlFor(format = ExcorCaptionFormat.SRT, translateTo = "de"))
        val chapter = ExcorChapter(title = "t", startSeconds = 0.0, endSeconds = null)
        listOf<Any?>(chapter.title, chapter.startSeconds, chapter.endSeconds)
        val metadata = ExcorMetadata(
            videoId = "v", title = null, author = null, channelId = null, channelUrl = null, durationSeconds = null,
            viewCount = null, likeCount = null, description = null, keywords = emptyList(), category = null,
            publishDate = null, uploadDate = null, thumbnails = listOf(thumbnail), isLive = null, isPrivate = null,
            isUnlisted = null, isFamilySafe = null, isShortsEligible = null, allowRatings = null,
            availableCountries = emptyList(), canonicalUrl = null, captions = listOf(caption), liveStatus = ExcorLiveStatus.LIVE,
            music = ExcorMusicInfo(track = "t", artists = listOf("a"), album = "b", releaseYear = null, releaseDate = null),
        )
        listOf<Any?>(
            metadata.title, metadata.author, metadata.channelId, metadata.channelUrl, metadata.durationSeconds, metadata.viewCount,
            metadata.likeCount, metadata.description, metadata.keywords, metadata.category, metadata.publishDate, metadata.uploadDate,
            metadata.thumbnails, metadata.isLive, metadata.isPrivate, metadata.isUnlisted, metadata.isFamilySafe,
            metadata.isShortsEligible, metadata.allowRatings, metadata.availableCountries, metadata.canonicalUrl,
            metadata.captions, metadata.liveStatus, metadata.music?.track, metadata.music?.artists, metadata.music?.album,
            metadata.music?.releaseYear, metadata.music?.releaseDate, thumbnail.url, thumbnail.width, thumbnail.height,
            caption.url, caption.languageCode, caption.name, caption.autoGenerated,
        )

        val candidate = ExcorAudioCandidate(url = "u", kbps = 1, mimeType = "m", format = ExcorAudioFormat.M4A)
        listOf<Any>(candidate.url, candidate.kbps, candidate.mimeType, candidate.format)
        assertEquals(listOf("M4A", "WEBM_OPUS", "OTHER"), ExcorAudioFormat.entries.map { it.name })
        assertEquals(listOf("NOT_LIVE", "LIVE", "UPCOMING", "WAS_LIVE", "POST_LIVE"), ExcorLiveStatus.entries.map { it.name })
        assertEquals(listOf("VIDEO", "PLAYLIST", "ALBUM", "ARTIST", "CHANNEL"), ExcorResultKind.entries.map { it.name })
        assertEquals(listOf("VIDEOS", "SHORTS", "CHANNELS", "PLAYLISTS", "MOVIES"), ExcorSearchType.entries.map { it.name })
        assertEquals(listOf("PROGRESSIVE", "HLS"), SoundCloudProtocol.entries.map { it.name })
        val refused = ExcorUnplayableException("v", ExcorUnplayableReason.OTHER, "UNPLAYABLE", "r")
        // Still an IllegalStateException, so callers that caught that keep working.
        val stillState: IllegalStateException = refused
        listOf<Any?>(refused.videoId, refused.reason, refused.status, refused.youtubeReason, stillState)
        assertEquals(
            listOf("AGE_RESTRICTED", "SIGN_IN_REQUIRED", "UNAVAILABLE", "UPCOMING", "GEO_RESTRICTED", "OTHER"),
            ExcorUnplayableReason.entries.map { it.name },
        )
        assertEquals(listOf("DEBUG", "INFO", "WARN", "ERROR"), ExcorLogLevel.entries.map { it.name })

        val session: ExcorSession = host.session()
        listOf<Any?>(session.cookie, session.visitorData, session.region, session.language)
        val services: ExcorHostServices = host
        services.log(ExcorLogLevel.INFO, "default trackId")
        listOf<Any?>(services.configStore.enabled, services.nowMs(), store.getString("k"), store.getLong("k"))
        store.putString("k", "v")
        store.putLong("k", 1)
        listOf<Any?>(host.tokenProvider, host.filesDir, host.httpClient)

        assertEquals(TokenProviderCapabilities(), tokens.capabilities)
        val capabilities = TokenProviderCapabilities(providers = PoTokenProviderKind.entries.toSet(), usesWebView = false)
        listOf<Any>(capabilities.providers, capabilities.usesWebView)
        assertEquals(
            listOf("WEB_BOTGUARD", "WEBPAGE_ATTESTATION", "ANDROID_DROIDGUARD", "IOS_ATTESTATION", "EXTERNAL"),
            PoTokenProviderKind.entries.map { it.name },
        )
        assertNull(tokens.getPoToken("v", "visitor"))
        tokens.prewarm()
        tokens.invalidateAttestation()
        tokens.close()
        val token = PoTokenResult(playerRequestToken = "a", streamingDataToken = "b", visitorData = "c")
        listOf(token.playerRequestToken, token.streamingDataToken, token.visitorData)

        val excor = Excor(host)
        val init: () -> Unit = excor::init
        when (val ref: ExcorRef? = excor.parse("u")) {
            is ExcorRef.Video -> listOf<Any?>(ref.videoId, ref.playlistId, ref.startSeconds)
            is ExcorRef.Playlist -> listOf(ref.playlistId)
            is ExcorRef.Album -> listOf(ref.browseId)
            is ExcorRef.Mix -> listOf(ref.playlistId)
            is ExcorRef.Channel -> listOf(ref.channelId)
            null -> Unit
        }
        val network: suspend () -> Unit = {
            val a: List<ExcorAudioCandidate> = excor.audioCandidates("v")
            val b: ExcorStream? = excor.extract("v", 128)
            val c: ExcorStream? = excor.extract(videoId = "v", maxKbps = 128, skipClients = setOf("WEB"), requireM4a = true)
            val d: ExcorVideoStream? = excor.extractVideo("v")
            val e: ExcorVideoStream? = excor.extractVideo(videoId = "v", maxHeight = 720, skipClients = setOf("WEB"), requireAvc = true)
            val f: ExcorMetadata? = excor.metadata("v")
            val audioTracks: List<ExcorAudioTrack>? = f?.audioTracks
            listOf(audioTracks)
            val g: ExcorFormats? = excor.formats("v")
            val channel: ExcorChannel? = excor.channel("UC")
            listOf<Any?>(channel?.channelId, channel?.title, channel?.handle, channel?.description, channel?.avatars, channel?.banners, channel?.tabs)
            val apple: ExcorAppleMusic = excor.appleMusic
            val ref: AppleMusicRef? = apple.parse("https://music.apple.com/us/album/x/1?i=2")
            listOf<Any?>(ref?.id, ref?.country, ref is AppleMusicRef.Song, ref is AppleMusicRef.Album, ref is AppleMusicRef.Artist)
            val song: AppleMusicSong? = apple.song(1, "us")
            song?.let {
                listOf<Any?>(it.id, it.title, it.artist, it.artistId, it.album, it.albumId, it.durationMs, it.trackNumber, it.trackCount)
                listOf<Any?>(it.discNumber, it.discCount, it.releaseDate, it.genre, it.isExplicit, it.artwork, it.url)
            }
            val album: AppleMusicAlbum? = apple.album(1, null)
            album?.let { listOf<Any?>(it.id, it.title, it.artist, it.artistId, it.trackCount, it.releaseDate, it.genre, it.copyright, it.isExplicit, it.artwork, it.url, it.songs) }
            val artist: AppleMusicArtist? = apple.artist(1, null, 5)
            artist?.let { listOf<Any?>(it.id, it.name, it.genre, it.url, it.albums) }
            val pictures: List<ExcorThumbnail> = apple.artistImages(1, "us")
            listOf(pictures)
            val songs: List<AppleMusicSong> = apple.searchSongs("q", null, 5)
            val albums: List<AppleMusicAlbum> = apple.searchAlbums("q", null, 5)
            listOf(songs, albums)
            val posts: ExcorPostPage = excor.channelPosts("UC")
            val morePosts: ExcorPostPage = excor.channelPostsMore("token")
            (posts.posts + morePosts.posts).forEach {
                listOf<Any?>(it.postId, it.text, it.links, it.publishedText, it.likeCount, it.images, it.video, it.playlistId)
            }
            listOf(posts.continuation)
            val tab: ExcorChannelPage = excor.channelTab(channelId = "UC", tab = ExcorChannelTab.SHORTS)
            val tabMore: ExcorChannelPage = excor.channelTabMore("token")
            listOf<Any?>(tab.items, tab.continuation, tabMore, ExcorChannelTab.entries.toList())
            val comments: ExcorCommentPage = excor.comments("v")
            val newest: ExcorCommentPage = excor.comments(videoId = "v", newestFirst = true)
            val replies: ExcorCommentPage = excor.commentsMore(continuation = "token")
            listOf<Any?>(comments.continuation, comments.totalCount, newest, replies)
            comments.comments.forEach {
                listOf<Any?>(it.commentId, it.text, it.authorName, it.authorChannelId, it.authorAvatarUrl, it.authorIsUploader,
                    it.authorIsVerified, it.publishedTime, it.likeCount, it.replyCount, it.isPinned, it.isHearted, it.repliesContinuation)
            }
            val chapters: List<ExcorChapter> = excor.chapters("v")
            val captionText: String = excor.captionText(track = caption, format = ExcorCaptionFormat.VTT, translateTo = "de")
            listOf<Any?>(chapters, captionText, excor.captionText(caption, ExcorCaptionFormat.JSON3))
            val manifest: ExcorManifest? = excor.manifest(videoId = "v", skipClients = setOf("WEB"))
            listOf<Any?>(manifest?.videoId, manifest?.kind == ExcorManifestKind.HLS || manifest?.kind == ExcorManifestKind.DASH, manifest?.url, manifest?.headers, manifest?.profileId, manifest?.isLive)
            g?.formats?.forEach { listOf<Any?>(it.itag, it.url, it.mimeType, it.kbps, it.contentLength, it.hasAudio, it.hasVideo, it.width, it.height, it.fps) }
            listOf<Any?>(g?.videoId, g?.clientName, g?.profileId, g?.headers)
            val sink = ExcorSink { bytes -> bytes.size }
            val format = ExcorFormat(1, "u", "m", 1, null, hasAudio = true, hasVideo = false, width = null, height = null, fps = null)
            val h: Long = excor.download(format, emptyMap(), sink)
            val i: Long = excor.download(format = format, headers = emptyMap(), sink = sink, from = 10, onProgress = { written, total -> listOf(written, total) })
            listOf(h, i)
            val j: ExcorMergePair? = excor.mergePair(g!!, maxHeight = 2160, container = ExcorContainer.WEBM)
            listOf<Any?>(j?.video, j?.audio, j?.container == ExcorContainer.MP4)
            val j2: ExcorMergePair? = g.mergePair(maxHeight = 1080, container = ExcorContainer.MP4)
            listOf<Any?>(j2)
            val k: ExcorPlaylist? = excor.playlist("PL")
            listOf<Any?>(k?.playlistId, k?.title, k?.description, k?.ownerName, k?.ownerChannelId, k?.thumbnails, k?.firstPage)
            val l: ExcorListPage = excor.playlistMore("token")
            l.items.forEach { listOf<Any?>(it.videoId, it.title, it.channelName, it.channelId, it.durationSeconds, it.thumbnails) }
            listOf<Any?>(l.continuation)
            val m: ExcorAlbum? = excor.album("MPREb_x")
            listOf<Any?>(m?.browseId, m?.playlistId, m?.title, m?.artist, m?.artistChannelId, m?.year, m?.thumbnails, m?.tracks)
            val n: ExcorArtist? = excor.artist("UC")
            listOf<Any?>(n?.channelId, n?.name, n?.description, n?.thumbnails, n?.topSongs, n?.songsPlaylistId, n?.videosPlaylistId)
            n?.releases?.forEach { listOf<Any?>(it.browseId, it.title, it.year, it.thumbnails) }
            val o: ExcorMix? = excor.mix("RD")
            val o2: ExcorMix? = excor.mix(playlistId = "RD", videoId = "v")
            listOf<Any?>(o?.playlistId, o?.title, o?.firstPage, o2)
            val p: ExcorListPage = excor.mixMore("token")
            val q: ExcorListPage = excor.related("v")
            val r: ExcorListPage = excor.relatedMore("token")
            listOf(p, q, r)
            val s: ExcorSearchPage = excor.search("q")
            val t: ExcorSearchPage = excor.searchMore("token")
            val u: ExcorSearchPage = excor.searchMusic("q")
            val typed: ExcorSearchPage = excor.search("q", ExcorSearchType.CHANNELS)
            val filter: ExcorSearchFilter = s.filters.first()
            val filtered: ExcorSearchPage = excor.search("q", filter)
            (s.results + t.results + u.results + typed.results + filtered.shorts).forEach {
                listOf<Any?>(it.kind == ExcorResultKind.VIDEO || it.kind == ExcorResultKind.CHANNEL, it.id, it.title, it.channelName, it.channelId, it.durationSeconds, it.thumbnails)
            }
            listOf<Any?>(s.continuation, filter.group, filter.label, filter.params, filter.selected)
            val suggestions: List<String> = excor.suggestions("q")
            listOf(suggestions)
            val soundCloud: ExcorSoundCloud = excor.soundCloud
            val isLink: Boolean = soundCloud.isLink("https://soundcloud.com/a/b")
            listOf(isLink)
            val track: SoundCloudTrack? = soundCloud.track("https://soundcloud.com/a/b")
            val set: SoundCloudPlaylist? = soundCloud.playlist("https://soundcloud.com/a/sets/b")
            listOf<Any?>(set?.id, set?.title, set?.uploader, set?.setType, set?.artworkUrl, set?.permalinkUrl, set?.tracks)
            track?.let {
                listOf<Any?>(it.id, it.title, it.uploader, it.uploaderUrl, it.artist, it.durationMs, it.artworkUrl, it.permalinkUrl, it.genre, it.isBlocked, it.hasDrm)
                val transcoding: SoundCloudTranscoding = it.transcodings.first()
                val protocol: SoundCloudProtocol = transcoding.protocol
                val stream: SoundCloudStream = soundCloud.stream(transcoding)
                val written: Long = soundCloud.download(transcoding, { _: ByteArray -> }) { _: Float -> }
                val plain: Long = soundCloud.download(transcoding, {})
                listOf(written, plain)
                listOf<Any?>(transcoding.preset, transcoding.mimeType, transcoding.isPreview, protocol, stream.url, stream.protocol, stream.mimeType, stream.isPreview)
            }
            listOf(a, b, c, d, e, f, init)
        }
        listOf(network)
        // A filter without params (the one in use) is refused before any request.
        assertFailsWith<IllegalArgumentException> { excor.search("q", ExcorSearchFilter("Type", "Channels", null, true)) }
        assertEquals(emptyList(), excor.suggestions(""))
        assertEquals(listOf(true, false), listOf("https://soundcloud.com/a/b", "https://youtu.be/dQw4w9WgXcQ").map(excor.soundCloud::isLink))
        assertEquals(AppleMusicRef.Artist(669771, "us"), excor.appleMusic.parse("https://music.apple.com/us/artist/rick-astley/669771"))
        excor.preferAudioLanguage("es-US")
        excor.preferAudioLanguage(null)
        val track = ExcorAudioTrack("en", "English original", isOriginal = true, isDefault = false, isDescriptive = false)
        listOf<Any?>(track.languageCode, track.name, track.isOriginal, track.isDefault, track.isDescriptive)
        excor.initializeFallback()
        assertNull(excor.headersFor("u"))
        assertNull(excor.onRefused("u"))
        excor.exclude("v", "p")
        excor.onSessionChanged()
        excor.close()
    }
}
