package com.vyonex

import com.vyonex.internal.primary.extraction.PoTokenResult
import com.vyonex.internal.primary.extraction.TokenProvider
import com.vyonex.internal.primary.extraction.TokenProviderCapabilities
import com.vyonex.internal.primary.extraction.strategy.PoTokenProviderKind
import kotlinx.coroutines.runBlocking
import okhttp3.OkHttpClient
import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNull

/** Compiles against every member of the public API the host app uses (BRIEF section 3). */
class ApiCheckTest {
    private val store = object : VyonExConfigStore {
        override val enabled: Boolean = false
        override fun getString(key: String): String? = null
        override fun getLong(key: String): Long? = null
        override fun putString(key: String, value: String) {}
        override fun putLong(key: String, value: Long) {}
    }

    private val tokens = object : TokenProvider {
        override suspend fun getPoToken(videoId: String, visitorData: String, cookie: String?): PoTokenResult? = null
    }

    private val host = object : VyonExHost {
        override suspend fun session() = VyonExSession(cookie = null, visitorData = null, region = "US", language = "en")
        override val configStore: VyonExConfigStore = store
        override fun nowMs(): Long = 0
        override fun log(level: VyonExLogLevel, message: String, trackId: String?) {}
        override val tokenProvider: TokenProvider = tokens
        override val filesDir: File? = null
        override val httpClient: OkHttpClient = OkHttpClient()
    }

    @Test
    fun publicApiCompiles() = runBlocking {
        val stream = VyonExStream(
            videoId = "v", url = "u", kbps = 1, mimeType = "m", loudnessDb = null,
            clientName = "c", profileId = "p", headers = emptyMap(),
        )
        val (videoId, url, kbps, mimeType, loudnessDb, clientName, profileId, headers) = stream
        listOf<Any?>(videoId, url, kbps, mimeType, loudnessDb, clientName, profileId, headers)

        val video = VyonExVideoStream(
            videoId = "v", url = "u", width = 1, height = 1, fps = 1, kbps = 1, mimeType = "m", audio = stream,
            clientName = "c", profileId = "p", headers = emptyMap(),
        )
        listOf<Any?>(video.videoId, video.url, video.width, video.height, video.fps, video.kbps, video.mimeType, video.audio, video.clientName, video.profileId, video.headers)
        val thumbnail = VyonExThumbnail(url = "u", width = 1, height = 1)
        val caption = VyonExCaptionTrack(url = "u", languageCode = "en", name = null, autoGenerated = true, isTranslatable = true)
        listOf<Any?>(caption.isTranslatable, caption.urlFor(VyonExCaptionFormat.VTT), caption.urlFor(format = VyonExCaptionFormat.SRT, translateTo = "de"))
        val chapter = VyonExChapter(title = "t", startSeconds = 0.0, endSeconds = null)
        listOf<Any?>(chapter.title, chapter.startSeconds, chapter.endSeconds)
        val metadata = VyonExMetadata(
            videoId = "v", title = null, author = null, channelId = null, channelUrl = null, durationSeconds = null,
            viewCount = null, likeCount = null, description = null, keywords = emptyList(), category = null,
            publishDate = null, uploadDate = null, thumbnails = listOf(thumbnail), isLive = null, isPrivate = null,
            isUnlisted = null, isFamilySafe = null, isShortsEligible = null, allowRatings = null,
            availableCountries = emptyList(), canonicalUrl = null, captions = listOf(caption), liveStatus = VyonExLiveStatus.LIVE,
            music = VyonExMusicInfo(track = "t", artists = listOf("a"), album = "b", releaseYear = null, releaseDate = null),
        )
        listOf<Any?>(
            metadata.title, metadata.author, metadata.channelId, metadata.channelUrl, metadata.durationSeconds, metadata.viewCount,
            metadata.likeCount, metadata.description, metadata.keywords, metadata.category, metadata.publishDate, metadata.uploadDate,
            metadata.thumbnails, metadata.isLive, metadata.isPrivate, metadata.isUnlisted, metadata.isFamilySafe,
            metadata.isShortsEligible, metadata.allowRatings, metadata.availableCountries, metadata.canonicalUrl,
            metadata.captions, metadata.liveStatus, metadata.music?.track, metadata.music?.artists, metadata.music?.album,
            metadata.music?.releaseYear, metadata.music?.releaseDate, thumbnail.url, thumbnail.width, thumbnail.height,
            caption.url, caption.languageCode, caption.name, caption.autoGenerated,
        )

        val candidate = VyonExAudioCandidate(url = "u", kbps = 1, mimeType = "m", format = VyonExAudioFormat.M4A)
        listOf<Any>(candidate.url, candidate.kbps, candidate.mimeType, candidate.format)
        assertEquals(listOf("M4A", "WEBM_OPUS", "OTHER"), VyonExAudioFormat.entries.map { it.name })
        assertEquals(listOf("NOT_LIVE", "LIVE", "UPCOMING", "WAS_LIVE", "POST_LIVE"), VyonExLiveStatus.entries.map { it.name })
        assertEquals(listOf("VIDEO", "PLAYLIST", "ALBUM", "ARTIST", "CHANNEL"), VyonExResultKind.entries.map { it.name })
        assertEquals(listOf("VIDEOS", "SHORTS", "CHANNELS", "PLAYLISTS", "MOVIES"), VyonExSearchType.entries.map { it.name })
        assertEquals(listOf("PROGRESSIVE", "HLS"), SoundCloudProtocol.entries.map { it.name })
        val refused = VyonExUnplayableException("v", VyonExUnplayableReason.OTHER, "UNPLAYABLE", "r")
        // Still an IllegalStateException, so callers that caught that keep working.
        val stillState: IllegalStateException = refused
        listOf<Any?>(refused.videoId, refused.reason, refused.status, refused.youtubeReason, stillState)
        assertEquals(
            listOf("AGE_RESTRICTED", "SIGN_IN_REQUIRED", "UNAVAILABLE", "UPCOMING", "GEO_RESTRICTED", "OTHER"),
            VyonExUnplayableReason.entries.map { it.name },
        )
        assertEquals(listOf("DEBUG", "INFO", "WARN", "ERROR"), VyonExLogLevel.entries.map { it.name })

        val session: VyonExSession = host.session()
        listOf<Any?>(session.cookie, session.visitorData, session.region, session.language)
        val services: VyonExHostServices = host
        services.log(VyonExLogLevel.INFO, "default trackId")
        listOf<Any?>(services.configStore.enabled, services.nowMs(), store.getString("k"), store.getLong("k"))
        store.putString("k", "v")
        store.putLong("k", 1)
        listOf<Any?>(host.tokenProvider, host.filesDir, host.httpClient)

        assertEquals(TokenProviderCapabilities(), tokens.capabilities)
        val capabilities = TokenProviderCapabilities(providers = PoTokenProviderKind.entries.toSet(), usesWebView = false)
        listOf<Any>(capabilities.providers, capabilities.usesWebView)
        assertEquals(
            listOf("WEB_BOTGUARD", "WEBPAGE_ATTESTATION", "ANDROID_DROIDGUARD", "IOS_ATTESTATION", "EXTERNAL"),
            PoTokenProviderKind.entries.map { it.name },
        )
        assertNull(tokens.getPoToken("v", "visitor"))
        tokens.prewarm()
        tokens.invalidateAttestation()
        tokens.close()
        val token = PoTokenResult(playerRequestToken = "a", streamingDataToken = "b", visitorData = "c")
        listOf(token.playerRequestToken, token.streamingDataToken, token.visitorData)

        val vyonEx = VyonEx(host)
        val init: () -> Unit = vyonEx::init
        when (val ref: VyonExRef? = vyonEx.parse("u")) {
            is VyonExRef.Video -> listOf<Any?>(ref.videoId, ref.playlistId, ref.startSeconds)
            is VyonExRef.Playlist -> listOf(ref.playlistId)
            is VyonExRef.Album -> listOf(ref.browseId)
            is VyonExRef.Mix -> listOf(ref.playlistId)
            is VyonExRef.Channel -> listOf(ref.channelId)
            null -> Unit
        }
        val network: suspend () -> Unit = {
            val a: List<VyonExAudioCandidate> = vyonEx.audioCandidates("v")
            val b: VyonExStream? = vyonEx.extract("v", 128)
            val c: VyonExStream? = vyonEx.extract(videoId = "v", maxKbps = 128, skipClients = setOf("WEB"), requireM4a = true)
            val d: VyonExVideoStream? = vyonEx.extractVideo("v")
            val e: VyonExVideoStream? = vyonEx.extractVideo(videoId = "v", maxHeight = 720, skipClients = setOf("WEB"), requireAvc = true)
            val f: VyonExMetadata? = vyonEx.metadata("v")
            val audioTracks: List<VyonExAudioTrack>? = f?.audioTracks
            listOf(audioTracks)
            val g: VyonExFormats? = vyonEx.formats("v")
            val channel: VyonExChannel? = vyonEx.channel("UC")
            listOf<Any?>(channel?.channelId, channel?.title, channel?.handle, channel?.description, channel?.avatars, channel?.banners, channel?.tabs)
            val tab: VyonExChannelPage = vyonEx.channelTab(channelId = "UC", tab = VyonExChannelTab.SHORTS)
            val tabMore: VyonExChannelPage = vyonEx.channelTabMore("token")
            listOf<Any?>(tab.items, tab.continuation, tabMore, VyonExChannelTab.entries.toList())
            val comments: VyonExCommentPage = vyonEx.comments("v")
            val newest: VyonExCommentPage = vyonEx.comments(videoId = "v", newestFirst = true)
            val replies: VyonExCommentPage = vyonEx.commentsMore(continuation = "token")
            listOf<Any?>(comments.continuation, comments.totalCount, newest, replies)
            comments.comments.forEach {
                listOf<Any?>(it.commentId, it.text, it.authorName, it.authorChannelId, it.authorAvatarUrl, it.authorIsUploader,
                    it.authorIsVerified, it.publishedTime, it.likeCount, it.replyCount, it.isPinned, it.isHearted, it.repliesContinuation)
            }
            val chapters: List<VyonExChapter> = vyonEx.chapters("v")
            val captionText: String = vyonEx.captionText(track = caption, format = VyonExCaptionFormat.VTT, translateTo = "de")
            listOf<Any?>(chapters, captionText, vyonEx.captionText(caption, VyonExCaptionFormat.JSON3))
            val manifest: VyonExManifest? = vyonEx.manifest(videoId = "v", skipClients = setOf("WEB"))
            listOf<Any?>(manifest?.videoId, manifest?.kind == VyonExManifestKind.HLS || manifest?.kind == VyonExManifestKind.DASH, manifest?.url, manifest?.headers, manifest?.profileId, manifest?.isLive)
            g?.formats?.forEach { listOf<Any?>(it.itag, it.url, it.mimeType, it.kbps, it.contentLength, it.hasAudio, it.hasVideo, it.width, it.height, it.fps) }
            listOf<Any?>(g?.videoId, g?.clientName, g?.profileId, g?.headers)
            val sink = VyonExSink { bytes -> bytes.size }
            val format = VyonExFormat(1, "u", "m", 1, null, hasAudio = true, hasVideo = false, width = null, height = null, fps = null)
            val h: Long = vyonEx.download(format, emptyMap(), sink)
            val i: Long = vyonEx.download(format = format, headers = emptyMap(), sink = sink, from = 10, onProgress = { written, total -> listOf(written, total) })
            listOf(h, i)
            val j: VyonExMergePair? = vyonEx.mergePair(g!!, maxHeight = 2160, container = VyonExContainer.WEBM)
            listOf<Any?>(j?.video, j?.audio, j?.container == VyonExContainer.MP4)
            val j2: VyonExMergePair? = g.mergePair(maxHeight = 1080, container = VyonExContainer.MP4)
            listOf<Any?>(j2)
            val k: VyonExPlaylist? = vyonEx.playlist("PL")
            listOf<Any?>(k?.playlistId, k?.title, k?.description, k?.ownerName, k?.ownerChannelId, k?.thumbnails, k?.firstPage)
            val l: VyonExListPage = vyonEx.playlistMore("token")
            l.items.forEach { listOf<Any?>(it.videoId, it.title, it.channelName, it.channelId, it.durationSeconds, it.thumbnails) }
            listOf<Any?>(l.continuation)
            val m: VyonExAlbum? = vyonEx.album("MPREb_x")
            listOf<Any?>(m?.browseId, m?.playlistId, m?.title, m?.artist, m?.artistChannelId, m?.year, m?.thumbnails, m?.tracks)
            val n: VyonExArtist? = vyonEx.artist("UC")
            listOf<Any?>(n?.channelId, n?.name, n?.description, n?.thumbnails, n?.topSongs, n?.songsPlaylistId, n?.videosPlaylistId)
            n?.releases?.forEach { listOf<Any?>(it.browseId, it.title, it.year, it.thumbnails) }
            val o: VyonExMix? = vyonEx.mix("RD")
            val o2: VyonExMix? = vyonEx.mix(playlistId = "RD", videoId = "v")
            listOf<Any?>(o?.playlistId, o?.title, o?.firstPage, o2)
            val p: VyonExListPage = vyonEx.mixMore("token")
            val q: VyonExListPage = vyonEx.related("v")
            val r: VyonExListPage = vyonEx.relatedMore("token")
            listOf(p, q, r)
            val s: VyonExSearchPage = vyonEx.search("q")
            val t: VyonExSearchPage = vyonEx.searchMore("token")
            val u: VyonExSearchPage = vyonEx.searchMusic("q")
            val typed: VyonExSearchPage = vyonEx.search("q", VyonExSearchType.CHANNELS)
            val filter: VyonExSearchFilter = s.filters.first()
            val filtered: VyonExSearchPage = vyonEx.search("q", filter)
            (s.results + t.results + u.results + typed.results + filtered.shorts).forEach {
                listOf<Any?>(it.kind == VyonExResultKind.VIDEO || it.kind == VyonExResultKind.CHANNEL, it.id, it.title, it.channelName, it.channelId, it.durationSeconds, it.thumbnails)
            }
            listOf<Any?>(s.continuation, filter.group, filter.label, filter.params, filter.selected)
            val suggestions: List<String> = vyonEx.suggestions("q")
            listOf(suggestions)
            val soundCloud: VyonExSoundCloud = vyonEx.soundCloud
            val isLink: Boolean = soundCloud.isLink("https://soundcloud.com/a/b")
            listOf(isLink)
            val track: SoundCloudTrack? = soundCloud.track("https://soundcloud.com/a/b")
            val set: SoundCloudPlaylist? = soundCloud.playlist("https://soundcloud.com/a/sets/b")
            listOf<Any?>(set?.id, set?.title, set?.uploader, set?.setType, set?.artworkUrl, set?.permalinkUrl, set?.tracks)
            track?.let {
                listOf<Any?>(it.id, it.title, it.uploader, it.uploaderUrl, it.artist, it.durationMs, it.artworkUrl, it.permalinkUrl, it.genre, it.isBlocked, it.hasDrm)
                val transcoding: SoundCloudTranscoding = it.transcodings.first()
                val protocol: SoundCloudProtocol = transcoding.protocol
                val stream: SoundCloudStream = soundCloud.stream(transcoding)
                val written: Long = soundCloud.download(transcoding, { _: ByteArray -> }) { _: Float -> }
                val plain: Long = soundCloud.download(transcoding, {})
                listOf(written, plain)
                listOf<Any?>(transcoding.preset, transcoding.mimeType, transcoding.isPreview, protocol, stream.url, stream.protocol, stream.mimeType, stream.isPreview)
            }
            listOf(a, b, c, d, e, f, init)
        }
        listOf(network)
        // A filter without params (the one in use) is refused before any request.
        assertFailsWith<IllegalArgumentException> { vyonEx.search("q", VyonExSearchFilter("Type", "Channels", null, true)) }
        assertEquals(emptyList(), vyonEx.suggestions(""))
        assertEquals(listOf(true, false), listOf("https://soundcloud.com/a/b", "https://youtu.be/dQw4w9WgXcQ").map(vyonEx.soundCloud::isLink))
        vyonEx.preferAudioLanguage("es-US")
        vyonEx.preferAudioLanguage(null)
        val track = VyonExAudioTrack("en", "English original", isOriginal = true, isDefault = false, isDescriptive = false)
        listOf<Any?>(track.languageCode, track.name, track.isOriginal, track.isDefault, track.isDescriptive)
        vyonEx.initializeFallback()
        assertNull(vyonEx.headersFor("u"))
        assertNull(vyonEx.onRefused("u"))
        vyonEx.exclude("v", "p")
        vyonEx.onSessionChanged()
        vyonEx.close()
    }
}
