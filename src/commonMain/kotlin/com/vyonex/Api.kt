data class VyonExThumbnail(val url: String, val width: Int, val height: Int)

/**
 * A subtitle track. [url] is signed, expires and is tied to the requesting IP. It returns YouTube's
 * XML; [urlFor] gives it in another format or translated. [isTranslatable]: YouTube translates it into the
 * metadata's `translationLanguages`.
 */
data class VyonExCaptionTrack(
    val url: String,
    val languageCode: String,
    val name: String?,
    val autoGenerated: Boolean,
    val isTranslatable: Boolean = false,
) {
    override fun toString() = "VyonExCaptionTrack(languageCode=$languageCode, name=$name, autoGenerated=$autoGenerated, isTranslatable=$isTranslatable)"
}

/** The subtitle formats YouTube writes (yt-dlp's list): WebVTT, SubRip, TTML, its JSON, and its own XML versions. */
enum class VyonExCaptionFormat(val query: String) { VTT("vtt"), SRT("srt"), TTML("ttml"), JSON3("json3"), SRV1("srv1"), SRV2("srv2"), SRV3("srv3") }

/**
 * This track in [format], translated into [translateTo] when given (a language code from the metadata's
 * `translationLanguages`). As yt-dlp: `xosf` is dropped (it adds position data that spoils VTT and JSON), and asking
 * for the track's own language is not a translation (YouTube damages the result).
 */
fun VyonExCaptionTrack.urlFor(format: VyonExCaptionFormat, translateTo: String? = null): String =
    URLBuilder(url).apply {
        listOf("fmt", "xosf", "tlang").forEach(parameters::remove)
        parameters.append("fmt", format.query)
        translateTo?.takeIf { it != languageCode }?.let { parameters.append("tlang", it) }
    }.buildString()

