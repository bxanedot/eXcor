/**
 * YouTube refused to play [videoId] to every client tried. [youtubeReason] is YouTube's own message, fit to show
 * (for example "This live event will begin in 27 hours."); [status] is its `playabilityStatus`.
 */
class VyonExUnplayableException(
    val videoId: String,
    val reason: VyonExUnplayableReason,
    val status: String?,
    val youtubeReason: String?,
) : IllegalStateException("VyonEx: video $videoId is unplayable ($status: $youtubeReason)")

/**
 * [AGE_RESTRICTED] and [SIGN_IN_REQUIRED] need an account, which VyonEx does not use. [UNAVAILABLE]: no such video,
 * or removed. [UPCOMING]: a live stream or premiere that has not started. [GEO_RESTRICTED]: not offered in the
 * requester's country. [OTHER]: any other refusal, such as a copyright block or a live stream without a recording.
 */
enum class VyonExUnplayableReason { AGE_RESTRICTED, SIGN_IN_REQUIRED, UNAVAILABLE, UPCOMING, GEO_RESTRICTED, OTHER }

/** Whether a video is, was or will be a live stream. [POST_LIVE]: just ended, still being processed. */
enum class VyonExLiveStatus { NOT_LIVE, LIVE, UPCOMING, WAS_LIVE, POST_LIVE }

/** One format of a video as `VyonEx.formats` lists it: audio, video, or both (combined). */
data class VyonExFormat(
    val itag: Int,
    val url: String,
    val mimeType: String,
    val kbps: Int,
    val contentLength: Long?,
    val hasAudio: Boolean,
    val hasVideo: Boolean,
    val width: Int?,
    val height: Int?,
    val fps: Int?,
) {
    // The URL may carry a PO token.
    override fun toString() =
        "VyonExFormat(itag=$itag, mimeType=$mimeType, kbps=$kbps, contentLength=$contentLength, " +
            "hasAudio=$hasAudio, hasVideo=$hasVideo, ${width}x$height@$fps)"
}

/**
 * Every format of a video from one client, all fetched with [headers]. They are not remembered for
 * `headersFor`/`onRefused`; when a download is refused, call `exclude(videoId, profileId)` and list again.
 */
data class VyonExFormats(
    val videoId: String,
    val formats: List<VyonExFormat>,
    val clientName: String,
    val profileId: String,
    val headers: Map<String, String>,
) {
    override fun toString() =
        "VyonExFormats(videoId=$videoId, formats=${formats.size}, clientName=$clientName, profileId=$profileId, headers=${headers.keys})"
}

/** A video format and an audio format that merge into one file without re-encoding. */
data class VyonExMergePair(val video: VyonExFormat, val audio: VyonExFormat, val container: VyonExContainer)

/** The best video and audio of these formats that merge into one [container] file, at most [maxHeight] tall; for shared code. */
fun VyonExFormats.mergePair(maxHeight: Int, container: VyonExContainer): VyonExMergePair? = mergePairOf(formats, maxHeight, container)

/** [WEBM]: VP9 + Opus, up to 4K and beyond. [MP4]: H.264 + AAC, up to 1080p (YouTube has no H.264 above it). */
enum class VyonExContainer { WEBM, MP4 }

