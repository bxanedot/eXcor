package com.vyonex

data class VyonExStream(
    val videoId: String,
    val url: String,
    val kbps: Int,
    val mimeType: String,
    val loudnessDb: Double?,
    val clientName: String,
    val profileId: String,
    val headers: Map<String, String>,
) {
    // The URL may carry a PO token and the headers a cookie.
    override fun toString() =
        "VyonExStream(videoId=$videoId, kbps=$kbps, mimeType=$mimeType, loudnessDb=$loudnessDb, " +
            "clientName=$clientName, profileId=$profileId, headers=${headers.keys})"
}

/**
 * A video stream. [url] is video only unless [audio] is null, in which case it is a combined
 * audio+video format; otherwise play [audio] alongside it (both use [headers]).
 */
data class VyonExVideoStream(
    val videoId: String,
    val url: String,
    val width: Int,
    val height: Int,
    val fps: Int,
    val kbps: Int,
    val mimeType: String,
    val audio: VyonExStream?,
    val clientName: String,
    val profileId: String,
    val headers: Map<String, String>,
) {
    // The URL may carry a PO token and the headers a cookie.
    override fun toString() =
        "VyonExVideoStream(videoId=$videoId, ${width}x$height@$fps, kbps=$kbps, mimeType=$mimeType, audio=$audio, " +
            "clientName=$clientName, profileId=$profileId, headers=${headers.keys})"
}

data class VyonExThumbnail(val url: String, val width: Int, val height: Int)

/**
 * A subtitle track. [url] is signed, expires and is tied to the requesting IP. It returns YouTube's
 * XML; append `&fmt=vtt` (or `json3`, `srv3`, `ttml`) for another format.
 */
data class VyonExCaptionTrack(val url: String, val languageCode: String, val name: String?, val autoGenerated: Boolean) {
    override fun toString() = "VyonExCaptionTrack(languageCode=$languageCode, name=$name, autoGenerated=$autoGenerated)"
}

/**
 * What YouTube says about a video. Fields a client did not report are null or empty. [durationSeconds] is null
 * for a stream that is live now or upcoming, where YouTube reports the time on air or zero.
 */
data class VyonExMetadata(
    val videoId: String,
    val title: String?,
    val author: String?,
    val channelId: String?,
    val channelUrl: String?,
    val durationSeconds: Long?,
    val viewCount: Long?,
    val likeCount: Long?,
    val description: String?,
    val keywords: List<String>,
    val category: String?,
    val publishDate: String?,
    val uploadDate: String?,
    val thumbnails: List<VyonExThumbnail>,
    /** Live right now ([liveStatus] is [VyonExLiveStatus.LIVE]); a past or upcoming stream is not live. */
    val isLive: Boolean?,
    val isPrivate: Boolean?,
    val isUnlisted: Boolean?,
    val isFamilySafe: Boolean?,
    val isShortsEligible: Boolean?,
    val allowRatings: Boolean?,
    val availableCountries: List<String>,
    val canonicalUrl: String?,
    val captions: List<VyonExCaptionTrack>,
    val liveStatus: VyonExLiveStatus?,
)

/** Whether a video is, was or will be a live stream. [POST_LIVE]: just ended, still being processed. */
enum class VyonExLiveStatus { NOT_LIVE, LIVE, UPCOMING, WAS_LIVE, POST_LIVE }

/** What a YouTube or YouTube Music link or ID points at; see `VyonEx.parse`. */
sealed class VyonExRef {
    /** A video, possibly opened from a list ([playlistId]) at [startSeconds]. */
    data class Video(val videoId: String, val playlistId: String? = null, val startSeconds: Int? = null) : VyonExRef()

    data class Playlist(val playlistId: String) : VyonExRef()

    /** A YouTube Music album page (`MPREb_…`). */
    data class Album(val browseId: String) : VyonExRef()

    /** A mix (`RD…`): a list YouTube generates from a seed. */
    data class Mix(val playlistId: String) : VyonExRef()
}

enum class VyonExAudioFormat { M4A, WEBM_OPUS, OTHER }

data class VyonExAudioCandidate(
    val url: String,
    val kbps: Int,
    val mimeType: String,
    val format: VyonExAudioFormat,
)

data class VyonExSession(
    val cookie: String?,
    val visitorData: String?,
    val region: String,
    val language: String,
) {
    override fun toString() =
        "VyonExSession(cookie=${presence(cookie)}, visitorData=${presence(visitorData)}, region=$region, language=$language)"
}

enum class VyonExLogLevel { DEBUG, INFO, WARN, ERROR }

interface VyonExConfigStore {
    val enabled: Boolean
    fun getString(key: String): String?
    fun getLong(key: String): Long?
    fun putString(key: String, value: String)
    fun putLong(key: String, value: Long)
}

interface VyonExHostServices {
    suspend fun session(): VyonExSession
    val configStore: VyonExConfigStore
    fun nowMs(): Long
    fun log(level: VyonExLogLevel, message: String, trackId: String? = null)
}

internal fun presence(value: String?) = if (value.isNullOrEmpty()) "missing" else "present"
