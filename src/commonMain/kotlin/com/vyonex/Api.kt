package com.vyonex

data class VyonExStream(
    val videoId: String,
    val url: String,
    val kbps: Int,
    val mimeType: String,
    val loudnessDb: Double?,
    val clientName: String,
    val profileId: String,
    val headers: Map<String, String>,
) {
    // The URL may carry a PO token and the headers a cookie.
    override fun toString() =
        "VyonExStream(videoId=$videoId, kbps=$kbps, mimeType=$mimeType, loudnessDb=$loudnessDb, " +
            "clientName=$clientName, profileId=$profileId, headers=${headers.keys})"
}

/**
 * A video stream. [url] is video only unless [audio] is null, in which case it is a combined
 * audio+video format; otherwise play [audio] alongside it (both use [headers]).
 */
data class VyonExVideoStream(
    val videoId: String,
    val url: String,
    val width: Int,
    val height: Int,
    val fps: Int,
    val kbps: Int,
    val mimeType: String,
    val audio: VyonExStream?,
    val clientName: String,
    val profileId: String,
    val headers: Map<String, String>,
) {
    // The URL may carry a PO token and the headers a cookie.
    override fun toString() =
        "VyonExVideoStream(videoId=$videoId, ${width}x$height@$fps, kbps=$kbps, mimeType=$mimeType, audio=$audio, " +
            "clientName=$clientName, profileId=$profileId, headers=${headers.keys})"
}

data class VyonExThumbnail(val url: String, val width: Int, val height: Int)

/**
 * A subtitle track. [url] is signed, expires and is tied to the requesting IP. It returns YouTube's
 * XML; append `&fmt=vtt` (or `json3`, `srv3`, `ttml`) for another format.
 */
data class VyonExCaptionTrack(val url: String, val languageCode: String, val name: String?, val autoGenerated: Boolean) {
    override fun toString() = "VyonExCaptionTrack(languageCode=$languageCode, name=$name, autoGenerated=$autoGenerated)"
}

/**
 * What YouTube says about a video. Fields a client did not report are null or empty. [durationSeconds] is null
 * for a stream that is live now or upcoming, where YouTube reports the time on air or zero.
 */
data class VyonExMetadata(
    val videoId: String,
    val title: String?,
    val author: String?,
    val channelId: String?,
    val channelUrl: String?,
    val durationSeconds: Long?,
    val viewCount: Long?,
    val likeCount: Long?,
    val description: String?,
    val keywords: List<String>,
    val category: String?,
    val publishDate: String?,
    val uploadDate: String?,
    val thumbnails: List<VyonExThumbnail>,
    /** Live right now ([liveStatus] is [VyonExLiveStatus.LIVE]); a past or upcoming stream is not live. */
    val isLive: Boolean?,
    val isPrivate: Boolean?,
    val isUnlisted: Boolean?,
    val isFamilySafe: Boolean?,
    val isShortsEligible: Boolean?,
    val allowRatings: Boolean?,
    val availableCountries: List<String>,
    val canonicalUrl: String?,
    val captions: List<VyonExCaptionTrack>,
    val liveStatus: VyonExLiveStatus?,
    /** Track details of a YouTube Music upload, read from its "Auto-generated by YouTube." description. */
    val music: VyonExMusicInfo?,
)

/** [releaseDate] is `YYYY-MM-DD` as YouTube writes it. */
data class VyonExMusicInfo(
    val track: String,
    val artists: List<String>,
    val album: String,
    val releaseYear: Int?,
    val releaseDate: String?,
)

/**
 * YouTube refused to play [videoId] to every client tried. [youtubeReason] is YouTube's own message, fit to show
 * (for example "This live event will begin in 27 hours."); [status] is its `playabilityStatus`.
 */
class VyonExUnplayableException(
    val videoId: String,
    val reason: VyonExUnplayableReason,
    val status: String?,
    val youtubeReason: String?,
) : IllegalStateException("VyonEx: video $videoId is unplayable ($status: $youtubeReason)")

/**
 * [AGE_RESTRICTED] and [SIGN_IN_REQUIRED] need an account, which VyonEx does not use. [UNAVAILABLE]: no such video,
 * or removed. [UPCOMING]: a live stream or premiere that has not started. [GEO_RESTRICTED]: not offered in the
 * requester's country. [OTHER]: any other refusal, such as a copyright block or a live stream without a recording.
 */
enum class VyonExUnplayableReason { AGE_RESTRICTED, SIGN_IN_REQUIRED, UNAVAILABLE, UPCOMING, GEO_RESTRICTED, OTHER }

/** Whether a video is, was or will be a live stream. [POST_LIVE]: just ended, still being processed. */
enum class VyonExLiveStatus { NOT_LIVE, LIVE, UPCOMING, WAS_LIVE, POST_LIVE }

/** One format of a video as `VyonEx.formats` lists it: audio, video, or both (combined). */
data class VyonExFormat(
    val itag: Int,
    val url: String,
    val mimeType: String,
    val kbps: Int,
    val contentLength: Long?,
    val hasAudio: Boolean,
    val hasVideo: Boolean,
    val width: Int?,
    val height: Int?,
    val fps: Int?,
) {
    // The URL may carry a PO token.
    override fun toString() =
        "VyonExFormat(itag=$itag, mimeType=$mimeType, kbps=$kbps, contentLength=$contentLength, " +
            "hasAudio=$hasAudio, hasVideo=$hasVideo, ${width}x$height@$fps)"
}

/**
 * Every format of a video from one client, all fetched with [headers]. They are not remembered for
 * `headersFor`/`onRefused`; when a download is refused, call `exclude(videoId, profileId)` and list again.
 */
data class VyonExFormats(
    val videoId: String,
    val formats: List<VyonExFormat>,
    val clientName: String,
    val profileId: String,
    val headers: Map<String, String>,
) {
    override fun toString() =
        "VyonExFormats(videoId=$videoId, formats=${formats.size}, clientName=$clientName, profileId=$profileId, headers=${headers.keys})"
}

/** A video format and an audio format that merge into one file without re-encoding. */
data class VyonExMergePair(val video: VyonExFormat, val audio: VyonExFormat, val container: VyonExContainer)

/** [WEBM]: VP9 + Opus, up to 4K and beyond. [MP4]: H.264 + AAC, up to 1080p (YouTube has no H.264 above it). */
enum class VyonExContainer { WEBM, MP4 }

/** Receives a download's bytes, in order. */
fun interface VyonExSink {
    fun write(bytes: ByteArray)
}

/** A video in a list (a playlist page, and later albums, mixes, search results). Fields YouTube left out are null or empty. */
data class VyonExListItem(
    val videoId: String,
    val title: String?,
    val channelName: String?,
    val channelId: String?,
    val durationSeconds: Long?,
    val thumbnails: List<VyonExThumbnail>,
)

/** More of a list; [continuation] asks for the next page and is null on the last one. */
data class VyonExListPage(val items: List<VyonExListItem>, val continuation: String?)

/** A playlist and its first page of videos; `VyonEx.playlistMore(continuation)` fetches the rest. */
data class VyonExPlaylist(
    val playlistId: String,
    val title: String?,
    val description: String?,
    val ownerName: String?,
    val ownerChannelId: String?,
    val thumbnails: List<VyonExThumbnail>,
    val firstPage: VyonExListPage,
)

/**
 * A YouTube Music album page (`MPREb_…`). [playlistId] (`OLAK5uy_…`) holds the same tracks as a playlist. Tracks carry
 * no thumbnails of their own; they share the album's.
 */
data class VyonExAlbum(
    val browseId: String,
    val playlistId: String?,
    val title: String?,
    val artist: String?,
    val artistChannelId: String?,
    val year: Int?,
    val thumbnails: List<VyonExThumbnail>,
    val tracks: List<VyonExListItem>,
)

/** An album, single or EP shown on an artist page; `VyonEx.album(browseId)` reads it. */
data class VyonExRelease(val browseId: String, val title: String?, val year: Int?, val thumbnails: List<VyonExThumbnail>)

/**
 * A YouTube Music artist page. [songsPlaylistId] and [videosPlaylistId] list all of the artist's songs and videos
 * (read them with `VyonEx.playlist`); [releases] are the albums, singles and EPs the page shows, up to 10 of each.
 */
data class VyonExArtist(
    val channelId: String,
    val name: String?,
    val description: String?,
    val thumbnails: List<VyonExThumbnail>,
    val topSongs: List<VyonExListItem>,
    val songsPlaylistId: String?,
    val videosPlaylistId: String?,
    val releases: List<VyonExRelease>,
)

/** What a YouTube or YouTube Music link or ID points at; see `VyonEx.parse`. */
sealed class VyonExRef {
    /** A video, possibly opened from a list ([playlistId]) at [startSeconds]. */
    data class Video(val videoId: String, val playlistId: String? = null, val startSeconds: Int? = null) : VyonExRef()

    data class Playlist(val playlistId: String) : VyonExRef()

    /** A YouTube Music album page (`MPREb_…`). */
    data class Album(val browseId: String) : VyonExRef()

    /** A mix (`RD…`): a list YouTube generates from a seed. */
    data class Mix(val playlistId: String) : VyonExRef()

    /** A channel (`UC…`), which on YouTube Music is an artist page; see `VyonEx.artist`. */
    data class Channel(val channelId: String) : VyonExRef()
}

enum class VyonExAudioFormat { M4A, WEBM_OPUS, OTHER }

data class VyonExAudioCandidate(
    val url: String,
    val kbps: Int,
    val mimeType: String,
    val format: VyonExAudioFormat,
)

data class VyonExSession(
    val cookie: String?,
    val visitorData: String?,
    val region: String,
    val language: String,
) {
    override fun toString() =
        "VyonExSession(cookie=${presence(cookie)}, visitorData=${presence(visitorData)}, region=$region, language=$language)"
}

enum class VyonExLogLevel { DEBUG, INFO, WARN, ERROR }

interface VyonExConfigStore {
    val enabled: Boolean
    fun getString(key: String): String?
    fun getLong(key: String): Long?
    fun putString(key: String, value: String)
    fun putLong(key: String, value: Long)
}

interface VyonExHostServices {
    suspend fun session(): VyonExSession
    val configStore: VyonExConfigStore
    fun nowMs(): Long
    fun log(level: VyonExLogLevel, message: String, trackId: String? = null)
}

internal fun presence(value: String?) = if (value.isNullOrEmpty()) "missing" else "present"
