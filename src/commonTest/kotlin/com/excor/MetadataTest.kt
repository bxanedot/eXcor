package com.excor

import com.excor.internal.metadataOf
import com.excor.internal.musicInfoOf
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonObject
import kotlinx.coroutines.test.runTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertNull
import kotlin.test.assertTrue
import kotlin.time.Duration.Companion.minutes

class MetadataTest {
    private val host = FakeHost()
    private val title = "Rick Astley - Never Gonna Give You Up (Official Video) (4K Remaster)"

    // The whole description, not a shortened one: 2376 UTF-16 units.
    private fun assertDescription(description: String?) {
        assertEquals(2376, description?.length)
        assertTrue(description!!.startsWith("The official video for “Never Gonna Give You Up” by Rick Astley"), description)
        assertTrue(description.endsWith("#OfficialMusicVideo"), description)
    }

    private fun assertFullWebMetadata(m: ExcorMetadata) {
        assertEquals("dQw4w9WgXcQ", m.videoId)
        assertEquals(title, m.title)
        assertEquals("Rick Astley", m.author)
        assertEquals("UCuAXFkgsw1L7xaCfnd5JJOw", m.channelId)
        assertEquals("http://www.youtube.com/@RickAstleyYT", m.channelUrl)
        assertEquals(213L, m.durationSeconds)
        assertEquals(1_830_812_666L, m.viewCount)
        assertEquals(19_495_333L, m.likeCount)
        assertDescription(m.description)
        assertEquals(27, m.keywords.size)
        assertEquals("Music", m.category)
        assertEquals("2009-10-24T23:57:33-07:00", m.publishDate)
        assertEquals("2009-10-24T23:57:33-07:00", m.uploadDate)
        // Five from videoDetails plus the microformat's 1280x720.
        assertEquals(6, m.thumbnails.size)
        assertTrue(m.thumbnails.any { it.width == 1920 && it.height == 1080 }, "${m.thumbnails}")
        assertTrue(m.thumbnails.any { it.width == 1280 && it.height == 720 }, "${m.thumbnails}")
        assertEquals(false, m.isLive)
        assertEquals(ExcorLiveStatus.NOT_LIVE, m.liveStatus)
        assertEquals(false, m.isPrivate)
        assertEquals(false, m.isUnlisted)
        assertEquals(true, m.isFamilySafe)
        assertEquals(false, m.isShortsEligible)
        assertEquals(true, m.allowRatings)
        assertEquals(249, m.availableCountries.size)
        assertEquals("https://www.youtube.com/watch?v=dQw4w9WgXcQ", m.canonicalUrl)
        assertCaptions(m.captions, "English (auto-generated)")
    }

    private fun assertCaptions(captions: List<ExcorCaptionTrack>, autoName: String) {
        assertEquals(listOf("en", "en", "de-DE", "ja", "pt-BR", "es-419"), captions.map { it.languageCode })
        assertEquals(listOf(false, true, false, false, false, false), captions.map { it.autoGenerated })
        assertEquals(autoName, captions[1].name)
        assertTrue(captions.all { it.url.startsWith("https://www.youtube.com/api/timedtext?") })
    }

    @Test
    fun webReportsEverything() = assertFullWebMetadata(metadataOf("dQw4w9WgXcQ", fixtureJson("player-response-web.json")))

    @Test
    fun visionOsHasNoMicroformat() {
        val m = metadataOf("dQw4w9WgXcQ", fixtureJson("player-response-visionos.json"))
        assertEquals(title, m.title)
        assertDescription(m.description)
        assertEquals(27, m.keywords.size)
        assertNull(m.category)
        assertNull(m.likeCount)
        assertEquals(emptyList(), m.availableCountries)
        // VISIONOS spells track names as runs rather than simpleText.
        assertCaptions(m.captions, "English (auto-generated)")
    }

    @Test
    fun captionsNeedingAPoTokenOrFromElsewhereAreDropped() {
        val track = { url: String -> """{"baseUrl":"$url","languageCode":"en","name":{"simpleText":"English"}}""" }
        val pr = Json.parseToJsonElement(
            """{"captions":{"playerCaptionsTracklistRenderer":{"captionTracks":[""" +
                track("https://www.youtube.com/api/timedtext?v=x&exp=xpe&lang=en") + "," +
                track("https://example.com/api/timedtext?v=x") + "," +
                track("https://www.youtube.com/api/timedtext?v=x&lang=en") + "]}}}",
        ).jsonObject
        assertEquals(listOf("https://www.youtube.com/api/timedtext?v=x&lang=en"), metadataOf("x", pr).captions.map { it.url })
    }

    @Test
    fun liveStatusFollowsYtDlp() {
        // Hand-written responses with only the flags yt-dlp reads. Durations of live-now and upcoming streams are dropped:
        // a 24/7 stream reported its years on air as lengthSeconds in a live run.
        fun meta(details: String, micro: String = "{}") = metadataOf(
            "x", Json.parseToJsonElement("""{"videoDetails":$details,"microformat":{"playerMicroformatRenderer":$micro}}""").jsonObject,
        ).let { Triple(it.liveStatus, it.isLive, it.durationSeconds) }
        assertEquals(Triple(ExcorLiveStatus.LIVE, true, null), meta("""{"isLive":true,"isLiveContent":true,"lengthSeconds":"121601512"}"""))
        assertEquals(Triple(ExcorLiveStatus.LIVE, true, null), meta("""{"isLiveContent":true}""", """{"liveBroadcastDetails":{"isLiveNow":true}}"""))
        assertEquals(Triple(ExcorLiveStatus.UPCOMING, false, null), meta("""{"isUpcoming":true,"isLiveContent":true,"lengthSeconds":"0"}"""))
        assertEquals(Triple(ExcorLiveStatus.WAS_LIVE, false, 3600L), meta("""{"isLiveContent":true,"lengthSeconds":"3600"}"""))
        assertEquals(Triple(ExcorLiveStatus.POST_LIVE, false, 7200L), meta("""{"isPostLiveDvr":true,"isLiveContent":true,"lengthSeconds":"7200"}"""))
        assertEquals(Triple(ExcorLiveStatus.NOT_LIVE, false, 213L), meta("""{"isLiveContent":false,"lengthSeconds":"213"}"""))
        assertEquals(Triple(null, null, null), meta("{}"))
    }

    @Test
    fun musicInfoComesFromAutoGeneratedDescriptions() {
        // Hand-written in the layout YouTube Music uses; the names are made up.
        val withArtistLine = "Provided to YouTube by Example Records\n\nPaper Lanterns · Mira Vale · The Tide\n\nHarbour Lights\n\n" +
            "℗ 2021 Example Records\n\nReleased on: 2021-03-05\n\nArtist: Mira Vale\nLyricist: Ana Kerr\n\nAuto-generated by YouTube."
        assertEquals(ExcorMusicInfo("Paper Lanterns", listOf("Mira Vale"), "Harbour Lights", 2021, "2021-03-05"), musicInfoOf(withArtistLine))
        val titleLineOnly = "Provided to YouTube by Example\n\nNorth · Mira Vale · The Tide\n\nCompass\n\n℗ 2019 Example\n\nAuto-generated by YouTube.\n"
        assertEquals(ExcorMusicInfo("North", listOf("Mira Vale", "The Tide"), "Compass", 2019, null), musicInfoOf(titleLineOnly))
        // A middle dot inside a name is not a separator; a ℗ line without a year leaves the year to the release date.
        val dotInName = "Provided to YouTube by Example\n\nEcho · half·light\n\nRooms\n\n℗ Example\n\nReleased on: 2018-11-02\n\nAuto-generated by YouTube."
        assertEquals(ExcorMusicInfo("Echo", listOf("half·light"), "Rooms", 2018, "2018-11-02"), musicInfoOf(dotInName))
        assertNull(musicInfoOf("Paper Lanterns · Mira Vale\n\nHarbour Lights\n\nOfficial video."))
        assertNull(metadataOf("dQw4w9WgXcQ", fixtureJson("player-response-web.json")).music)
    }

    @Test
    fun tvHasNeitherTitleNorDescription() {
        val m = metadataOf("dQw4w9WgXcQ", fixtureJson("player-response-tv_samsung.json"))
        assertNull(m.title)
        assertNull(m.description)
        assertEquals(213L, m.durationSeconds)
    }

    @Test
    fun engineAsksWebFirst() = runTest(timeout = 5.minutes) {
        // WEB needs the player's signatureTimestamp, so the captured player is prepared first.
        assertFullWebMetadata(assertNotNull(fixtureEngine(host).metadata("dQw4w9WgXcQ")))
    }

    @Test
    fun engineFallsBackToVisionOs() = runTest {
        val m = assertNotNull(fixtureEngine(host, failing = setOf("/iframe_api")).metadata("dQw4w9WgXcQ"))
        assertEquals(title, m.title)
        assertNull(m.category)
        assertTrue(host.logs.any { it.first == ExcorLogLevel.WARN && it.second.startsWith("Excor: WEB metadata failed") }, "${host.logs}")
    }
}
