package com.excor

import io.ktor.client.request.HttpRequestData
import io.ktor.http.parseQueryString
import kotlinx.coroutines.test.runTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertNull
import kotlin.test.assertTrue

class CaptionsTest {
    private val host = FakeHost()
    private val track = ExcorCaptionTrack(
        "https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en&xosf=1&fmt=srv3&signature=S", "en", "English", false, true,
    )

    private fun queryOf(url: String) = parseQueryString(url.substringAfter('?'))

    @Test
    fun formatsAndTranslationsFollowYtDlp() {
        val vtt = queryOf(track.urlFor(ExcorCaptionFormat.VTT))
        assertEquals(listOf("vtt"), vtt.getAll("fmt"))
        // xosf adds position data that spoils VTT and JSON; the signature stays.
        assertNull(vtt["xosf"])
        assertEquals("S", vtt["signature"])
        assertEquals("de", queryOf(track.urlFor(ExcorCaptionFormat.SRT, translateTo = "de"))["tlang"])
        // "Translating" into the track's own language damages it, so it is not asked for.
        assertNull(queryOf(track.urlFor(ExcorCaptionFormat.SRT, translateTo = "en"))["tlang"])
    }

    @Test
    fun metadataListsTracksAndTranslationLanguages() = runTest {
        val metadata = assertNotNull(fixtureEngine(host).metadata("dQw4w9WgXcQ"))
        val english = metadata.captions.first { it.languageCode == "en" && !it.autoGenerated }
        assertTrue(english.isTranslatable)
        // WEB reports YouTube's full list of translation languages.
        assertEquals(156, metadata.translationLanguages.size)
        assertTrue(metadata.translationLanguages["de"].orEmpty().isNotEmpty(), "${metadata.translationLanguages}")
    }

    @Test
    fun captionTextIsFetchedInTheChosenFormat() = runTest {
        val requests = mutableListOf<HttpRequestData>()
        val text = fixtureEngine(host, requests = requests).captionText(track, ExcorCaptionFormat.VTT, "de")
        assertTrue(text.startsWith("WEBVTT"))
        val request = requests.single { it.url.encodedPath == "/api/timedtext" }
        assertEquals("vtt" to "de", request.url.parameters["fmt"] to request.url.parameters["tlang"])
    }

    @Test
    fun onlyYouTubeCaptionUrlsAreFetched() = runTest {
        val elsewhere = track.copy(url = "https://example.com/api/timedtext?v=x")
        assertTrue(runCatching { fixtureEngine(host).captionText(elsewhere, ExcorCaptionFormat.VTT, null) }.exceptionOrNull() is IllegalArgumentException)
    }
}
